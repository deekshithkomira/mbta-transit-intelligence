"""Run every analysis, write dashboard JSON to site/data/ and a findings report."""
from __future__ import annotations

import json
import logging
from datetime import UTC, datetime

from mbta_ti import config
from mbta_ti.analysis import (
    experience,
    fare_integrity,
    reliability,
    ridership,
    short_hop,
    slow_zones,
    solutions,
    stations,
)

log = logging.getLogger(__name__)

MODULES = {
    "ridership": ridership,
    "reliability": reliability,
    "slow_zones": slow_zones,
    "stations": stations,
    "experience": experience,
    "fare_integrity": fare_integrity,
    "short_hop": short_hop,
}

SECTION_TITLES = {
    "ridership": "Ridership recovery & forecast",
    "reliability": "Bus & Commuter Rail reliability",
    "slow_zones": "Slow zones & rider delay",
    "stations": "Station demand",
    "experience": "Rider experience, accessibility & fare equity",
    "fare_integrity": "Fare integrity (decision models)",
    "short_hop": "Short-Hop distance-based fare",
}


def _default(o):
    if hasattr(o, "item"):
        return o.item()
    return str(o)


def _write_playbook_md(playbook: dict) -> None:
    import re
    strip = lambda t: re.sub(r"<[^>]+>", "", re.sub(r"</?b>", "**", t))  # noqa: E731
    out = ["# Solutions playbook", "",
           "_Generated by `mbta-ti analyze`; numbers are pulled from the analysis outputs._", "",
           strip(playbook["intro"]), ""]
    for i, s in enumerate(playbook["items"], 1):
        out += [f"## {i}. {s['title']}", f"**Problem area:** {s['problem']}", "",
                strip(s["summary"]), ""] + [f"- {strip(a)}" for a in s["actions"]] + \
               ["", f"_Evidence:_ {s['evidence']}", ""]
    out += ["Full citations: [research_evidence.md](research_evidence.md)."]
    (config.ROOT / "docs" / "solutions_playbook.md").write_text("\n".join(out) + "\n")


def network_geo() -> dict:
    net = json.loads((config.RAW / "v3_network.json").read_text())
    return {"routes": [{k: r[k] for k in ("id", "name", "color", "polylines")}
                       for r in net["routes"]],
            "stops": net["stops"]}


def run() -> None:
    config.SITE_DATA.mkdir(parents=True, exist_ok=True)
    config.REPORTS.mkdir(parents=True, exist_ok=True)
    findings, results = {}, {}
    for name, module in MODULES.items():
        log.info("analysis: %s", name)
        result = module.run()
        results[name] = result
        findings[name] = result["findings"]
        (config.SITE_DATA / f"{name}.json").write_text(
            json.dumps(result, default=_default, separators=(",", ":")))
    # Rider app (site/app): station graph + fare rules, consumed by site/app/fare.js
    app_data = config.ROOT / "site" / "app" / "data"
    app_data.mkdir(parents=True, exist_ok=True)
    shr = results["short_hop"]
    (app_data / "network.json").write_text(json.dumps(
        {"rules": shr["rules"], "flat_fare": shr["flat_fare"], "graph": shr["graph"],
         "examples": shr["examples"]}, default=_default, separators=(",", ":")))
    playbook = solutions.run(results)
    (config.SITE_DATA / "solutions.json").write_text(json.dumps(playbook, default=_default))
    _write_playbook_md(playbook)
    (config.SITE_DATA / "network.json").write_text(
        json.dumps(network_geo(), separators=(",", ":")))
    manifest = json.loads((config.RAW / "manifest.json").read_text())
    meta = {"generated_at": datetime.now(UTC).isoformat(timespec="seconds"),
            "sources": [{"key": k, "title": v["title"], "url": v["url"]}
                        for k, v in sorted(manifest.items())],
            "findings": findings}
    (config.SITE_DATA / "meta.json").write_text(json.dumps(meta, indent=1))

    lines = ["# Key findings", "",
             f"_Auto-generated by `mbta-ti analyze` on {meta['generated_at'][:10]} from "
             f"official MBTA open data. Every figure below is computed, not typed._", ""]
    for name, items in findings.items():
        lines += [f"## {SECTION_TITLES[name]}", ""] + [f"- {f}" for f in items] + [""]
    lines += ["## Sources", ""] + [f"- [{s['title']}]({s['url']})" for s in meta["sources"]]
    (config.REPORTS / "findings.md").write_text("\n".join(lines) + "\n")
    log.info("wrote %s", config.REPORTS / "findings.md")
